// Generates web/lib/api-types.ts from the FastAPI OpenAPI schema (TASK-052, D-011).
//
//   pnpm api:types            write the file
//   pnpm api:types --check    exit 1 if the file on disk is not what the API generates today
//   --out <path>              write or check another file (the tests use it)
//
// The schema comes from `python -m api.openapi`, which reads `app.openapi()` in process: the
// schema route is behind the JWT, and a running server would add a database and a token.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import openapiTS, { astToString } from "openapi-typescript";

const WEB = fileURLToPath(new URL("..", import.meta.url));
const PYTHON_DIR = resolve(WEB, "../python");

/** The committed file, and the name drift messages give it. */
export const OUTPUT_PATH = join(WEB, "lib/api-types.ts");
const OUTPUT_NAME = "web/lib/api-types.ts";

const HEADER = `/**
 * Generated by \`pnpm api:types\` from the FastAPI OpenAPI schema (python/api/src/api/main.py).
 * Do not edit: change a response model in the API, then run the command again. A test
 * (web/lib/api-types.test.ts) fails when this file is out of date.
 */

`;

/** The API's OpenAPI schema, as the parsed JSON \`python -m api.openapi\` prints. */
export function dumpSchema() {
  const run = spawnSync("uv", ["--directory", PYTHON_DIR, "run", "python", "-m", "api.openapi"], {
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
  });
  if (run.error) throw new Error(`could not run uv: ${run.error.message}`);
  if (run.status !== 0) throw new Error(`python -m api.openapi exited ${run.status}:\n${run.stderr}`);
  return JSON.parse(run.stdout);
}

/** The contents of the generated file for a schema: LF line endings, one trailing newline. */
export async function generate(schema) {
  const body = astToString(await openapiTS(schema));
  return `${HEADER}${body}`.replaceAll("\r\n", "\n").trimEnd() + "\n";
}

/**
 * Compare a fresh generation with the file on disk. CRLF on the disk side is ignored, because a
 * Windows checkout may convert line endings. `message` is empty when there is no drift.
 */
export function checkDrift(generated, onDisk) {
  if (generated === onDisk.replaceAll("\r\n", "\n")) return { code: 0, message: "" };
  return {
    code: 1,
    message: `${OUTPUT_NAME} is out of date with the API's OpenAPI schema. Run \`pnpm api:types\` and commit the result.`,
  };
}

async function main(args) {
  const check = args.includes("--check");
  const outIndex = args.indexOf("--out");
  const out = outIndex === -1 ? OUTPUT_PATH : resolve(args[outIndex + 1]);
  const generated = await generate(dumpSchema());

  if (check) {
    const drift = checkDrift(generated, readFileSync(out, "utf8"));
    if (drift.code !== 0) console.error(drift.message);
    return drift.code;
  }
  writeFileSync(out, generated);
  console.log(`wrote ${out === OUTPUT_PATH ? OUTPUT_NAME : out}`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.exitCode = await main(process.argv.slice(2));
}
