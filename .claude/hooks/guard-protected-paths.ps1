<#
  PreToolUse hook: blocks Edit/Write on files matching "protectedPaths" in .claude/kit.json.

  Patterns use PowerShell -like wildcards, matched case-insensitively against the path
  relative to the project root with forward slashes. "*" also matches across folders,
  so "*.pem" matches "certs/dev/server.pem".

  Hook contract:
    exit 0 -> allowed
    exit 2 -> blocked; stderr tells Claude why

  Fails open (allows the edit) if the payload or config can't be read.
  Compatible with Windows PowerShell 5.1 and PowerShell 7+.
#>
$ErrorActionPreference = 'Continue'

try {
    $raw = [Console]::In.ReadToEnd()
    if ([string]::IsNullOrWhiteSpace($raw)) { exit 0 }
    $payload = $raw | ConvertFrom-Json
} catch {
    exit 0
}

$projectDir = $env:CLAUDE_PROJECT_DIR
if ([string]::IsNullOrWhiteSpace($projectDir)) { $projectDir = $payload.cwd }
if ([string]::IsNullOrWhiteSpace($projectDir)) { $projectDir = (Get-Location).Path }

$configPath = Join-Path $projectDir '.claude/kit.json'
if (-not (Test-Path -LiteralPath $configPath)) { exit 0 }
try {
    $config = Get-Content -LiteralPath $configPath -Raw | ConvertFrom-Json
} catch {
    exit 0
}

$rules = @($config.protectedPaths | Where-Object { $_ -and -not [string]::IsNullOrWhiteSpace($_.pattern) })
if ($rules.Count -eq 0) { exit 0 }

$filePath = $payload.tool_input.file_path
if ([string]::IsNullOrWhiteSpace($filePath)) { $filePath = $payload.tool_input.notebook_path }
if ([string]::IsNullOrWhiteSpace($filePath)) { exit 0 }

$root = [System.IO.Path]::GetFullPath($projectDir).TrimEnd('\', '/')
$fullFile = [System.IO.Path]::GetFullPath($filePath)
if (-not $fullFile.StartsWith($root, [System.StringComparison]::OrdinalIgnoreCase)) { exit 0 }
$rel = $fullFile.Substring($root.Length).TrimStart('\', '/').Replace('\', '/')

foreach ($rule in $rules) {
    $pattern = ([string]$rule.pattern).Replace('\', '/')
    if ($rel -like $pattern) {
        $reason = 'protected'
        if (-not [string]::IsNullOrWhiteSpace($rule.reason)) { $reason = [string]$rule.reason }
        [Console]::Error.WriteLine("Blocked: '$rel' matches protected pattern '$pattern' in .claude/kit.json ($reason).")
        [Console]::Error.WriteLine('Do not edit this file or work around the block. If the change is genuinely required, stop and ask the user; they can remove the rule temporarily.')
        exit 2
    }
}
exit 0
