<#
  Regenerates docs/tasks/INDEX.md from the front matter and Metrics section of every task file.
  Task files are the source of truth. INDEX.md is git-ignored (docs/tasks/.gitignore) and
  regenerated on demand, so parallel task branches never conflict on it.

  Usage (from anywhere in the repo):
    powershell -NoProfile -ExecutionPolicy Bypass -File .claude/scripts/build-index.ps1
    powershell -NoProfile -ExecutionPolicy Bypass -File .claude/scripts/build-index.ps1 -Check   # exit 1 if INDEX.md is stale

  Compatible with Windows PowerShell 5.1 and PowerShell 7+.
#>
param([switch]$Check)

$ErrorActionPreference = 'Stop'
. "$PSScriptRoot\lib-tasks.ps1"

$root = Get-KitRoot
$tasks = @(Get-Tasks $root)
$byId = @{}
$duplicates = New-Object System.Collections.Generic.List[string]
foreach ($t in $tasks) {
    if ($byId.ContainsKey($t.Id)) { $duplicates.Add($t.Id) } else { $byId[$t.Id] = $t }
}

function Cell([string]$s) { if ([string]::IsNullOrWhiteSpace($s)) { return '' } return $s.Replace('|', '\|') }
function Metric($t, [string]$k) { if ($t.Metrics.ContainsKey($k)) { return Cell $t.Metrics[$k] } return '' }

$nl = "`n"
$sb = New-Object System.Text.StringBuilder
[void]$sb.Append('# Task board' + $nl + $nl)
[void]$sb.Append('<!-- GENERATED by .claude/scripts/build-index.ps1. Do not edit; edit the task files and rerun. -->' + $nl + $nl)

$order = @('In progress', 'Review', 'Blocked', 'Ready', 'Draft', 'Done')
$counts = @()
foreach ($s in $order) {
    $n = @($tasks | Where-Object { $_.Status -eq $s }).Count
    if ($n -gt 0) { $counts += "$s $n" }
}
if ($counts.Count -gt 0) { [void]$sb.Append('**' + ($counts -join ' / ') + '**' + $nl + $nl) }

[void]$sb.Append('| ID | Title | Status | Size | Model | Autonomy | Plan | Depends on | Verify rounds | Review rounds | First-pass AC FAILs |' + $nl)
[void]$sb.Append('|----|-------|--------|------|-------|----------|------|------------|---------------|---------------|---------------------|' + $nl)
foreach ($t in $tasks) {
    $deps = ($t.DependsOn -join ', ')
    $row = '| [' + (Cell $t.Id) + '](' + $t.FileName + ') | ' + (Cell $t.Title) + ' | ' + (Cell $t.Status) + ' | ' + (Cell $t.Size) +
           ' | ' + (Cell $t.Model) + ' | ' + (Cell $t.Autonomy) + ' | ' + (Cell $t.PlanStatus) + ' | ' + (Cell $deps) +
           ' | ' + (Metric $t 'Verify rounds') + ' | ' + (Metric $t 'Review rounds') + ' | ' + (Metric $t 'First-pass AC FAILs') + ' |'
    [void]$sb.Append($row + $nl)
}

# ---- Warnings ---------------------------------------------------------------
$warnings = New-Object System.Collections.Generic.List[string]
foreach ($d in $duplicates) { $warnings.Add("Duplicate task id $d") }
foreach ($t in $tasks) {
    if ([string]::IsNullOrWhiteSpace($t.Id)) { $warnings.Add("$($t.FileName) has no id in its front matter") }
    foreach ($d in $t.DependsOn) {
        if (-not $byId.ContainsKey($d)) { $warnings.Add("$($t.Id) depends on unknown task $d") }
    }
    if ($t.Status -eq 'Review') { $warnings.Add("$($t.Id) is in Review on this branch: if its PR is merged, set status: Done") }
    if ($t.PlanStatus -eq 'approved' -and [string]::IsNullOrWhiteSpace($t.PlannedAtCommit)) {
        $warnings.Add("$($t.Id) has an approved plan but no planned_at_commit; the staleness check can't run")
    }
    if ($t.Status -eq 'Ready' -and $t.PlanStatus -eq 'approved' -and -not (Test-DepsDone $t $byId)) {
        $warnings.Add("$($t.Id) plan is approved but dependencies are not Done; it will wait")
    }
}
if ($warnings.Count -gt 0) {
    [void]$sb.Append($nl + '## Warnings' + $nl + $nl)
    foreach ($w in $warnings) { [void]$sb.Append('- ' + $w + $nl) }
}

[void]$sb.Append($nl + '## Reading the metrics' + $nl + $nl)
[void]$sb.Append('- First-pass AC FAILs > 0 on most tasks: specs too loose or plans not covering every AC. Tighten ACs in /new-task.' + $nl)
[void]$sb.Append('- Verify rounds >= 3 regularly: tasks too large, or verify.fast is missing a check.' + $nl)
[void]$sb.Append('- Review rounds >= 2 regularly: scope creep or rule violations. Add repeat offenders to CLAUDE.md Gotchas.' + $nl)
[void]$sb.Append('- Plan revisions after approval > 0: plans approved too quickly, or Phase 1 exploration too shallow.' + $nl)

$text = $sb.ToString()
$indexPath = Join-Path $root 'docs/tasks/INDEX.md'

if ($Check) {
    $current = ''
    if (Test-Path -LiteralPath $indexPath) { $current = [System.IO.File]::ReadAllText($indexPath).Replace("`r`n", "`n") }
    if ($current -ne $text) {
        Write-Host 'docs/tasks/INDEX.md is out of date. Run .claude/scripts/build-index.ps1 and commit.'
        exit 1
    }
    Write-Host 'docs/tasks/INDEX.md is up to date.'
    exit 0
}

Write-Utf8File $indexPath $text
Write-Host "Wrote docs/tasks/INDEX.md ($($tasks.Count) tasks, $($warnings.Count) warnings)."
